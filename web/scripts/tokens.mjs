// Writes src/ui/tokens.css from src/ui/tokens.json, the "Marshal" design system's tokens (see src/ui/README.md).
// Run with `npm run gen:tokens` after replacing tokens.json with a new export from the design system.
import { readFileSync, writeFileSync } from 'node:fs'

const root = new URL('../src/ui/', import.meta.url)
const tokens = JSON.parse(readFileSync(new URL('tokens.json', root), 'utf8'))

const themed = [...tokens.color.tokens, ...tokens.shadow.tokens]
const themeBlock = (theme) => themed.map((token) => `  --${token.name}: ${typeof token.value === 'string' ? token.value : token.value[theme]};`).join('\n')
const plain = [...tokens.spacing.tokens, ...tokens.radius.tokens].map((token) => `  --${token.name}: ${token.value};`)
const families = Object.entries(tokens.type.families).map(([name, stack]) => `  --font-${name}: ${stack};`)
const styles = tokens.type.groups.flatMap((group) =>
  group.styles.flatMap((style) => [
    `  --text-${style.name}: ${style.fontWeight} ${style.fontSize}/${style.lineHeight} var(--font-${style.family});`,
    `  --tracking-${style.name}: ${style.letterSpacing};`,
  ]),
)

const css = `/* Generated by scripts/tokens.mjs from tokens.json. Do not edit; change the design system and export again. */
:root,
[data-theme='light'] {
  color-scheme: light;
${themeBlock('light')}
}

[data-theme='dark'] {
  color-scheme: dark;
${themeBlock('dark')}
}

@media (prefers-color-scheme: dark) {
  :root:not([data-theme='light']) {
    color-scheme: dark;
${themeBlock('dark').replace(/^/gm, '  ')}
  }
}

:root {
${[...families, ...plain, ...styles].join('\n')}
}
`
writeFileSync(new URL('tokens.css', root), css)
console.log(`tokens.css: ${themed.length} themed, ${plain.length + families.length + styles.length} shared tokens`)
